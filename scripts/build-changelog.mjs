/**
 * Compiles the two changelog design templates with the real 44 releases.
 *
 * Same pattern as build-blog.mjs and build-roadmap.mjs: the design ships with sample releases
 * so it previews in Claude Design, and this swaps in the real data. Markup, CSS and behaviour
 * are untouched.
 *
 * Two things the design cannot do on its own, handled here:
 *
 * 1. RELEASE HREFS. Every release row and both prev/next links are hardcoded to
 *    "CoachRx Changelog Entry.dc.html", so fixLinks() collapses all 44 of them to /changelog
 *    and the whole archive becomes one link repeated. We set the real per-release href after
 *    compiling, matching anchors in document order. Same approach as linkifyChips().
 *
 * 2. hasNext / isLatest. Both are sc-if conditions, which resolve at COMPILE time, so one
 *    compiled template cannot serve both the newest release (no Next link) and the other 43
 *    (Next link present). So the entry is compiled twice into two variants and the route picks
 *    per release. Compiling 44 copies would work too but bloats the bundle for no gain.
 *
 * Outputs src/generated/{changelog-index,changelog-entry,changelog-entry-latest}.ts
 */
import fs from "node:fs";
import path from "node:path";
import * as cheerio from "cheerio";
import { compileDesign } from "./dc-compile.mjs";

const ROOT = process.cwd();
const DROOT = path.join(ROOT, "design");
const findDesign = (f) => {
  const d = path.join(DROOT, f);
  if (fs.existsSync(d)) return d;
  for (const e of fs.readdirSync(DROOT, { withFileTypes: true })) {
    if (!e.isDirectory()) continue;
    const n = path.join(DROOT, e.name, f);
    if (fs.existsSync(n)) return n;
  }
  return d;
};
const OUT = path.join(ROOT, "src", "generated");
const SRC_INDEX = findDesign("CoachRx Changelog.dc.html");
const SRC_ENTRY = findDesign("CoachRx Changelog Entry.dc.html");

for (const [label, f] of [["index", SRC_INDEX], ["entry", SRC_ENTRY]]) {
  if (!fs.existsSync(f)) {
    console.log(`\nbuild-changelog:\n  skip (${label} design file not built yet)`);
    process.exit(0);
  }
}

const RELEASES = JSON.parse(fs.readFileSync(path.join(ROOT, "src", "data", "changelog.json"), "utf8"))
  .filter((r) => !r.draft)
  .sort((a, b) => (a.date < b.date ? 1 : -1));

const MONTHS = ["January","February","March","April","May","June","July","August","September","October","November","December"];
const mName = (d) => `${MONTHS[parseInt(d.slice(5, 7), 10) - 1]} ${d.slice(0, 4)}`;
const shortDate = (d) =>
  `${MONTHS[parseInt(d.slice(5, 7), 10) - 1].slice(0, 3).toUpperCase()} ${parseInt(d.slice(8, 10), 10)}`;
const longDate = (d) =>
  `${MONTHS[parseInt(d.slice(5, 7), 10) - 1].slice(0, 3).toUpperCase()} ${parseInt(d.slice(8, 10), 10)}, ${d.slice(0, 4)}`;

const rel = RELEASES.map((r) => ({
  slug: r.slug,
  date: r.date,
  description: r.description,
  title: `${mName(r.date)} release`,
  month: mName(r.date),
  year: r.date.slice(0, 4),
  dateShort: shortDate(r.date),
  dateLabel: longDate(r.date),
  href: `/changelog/${r.slug}`,
}));

const byYear = {};
for (const r of rel) (byYear[r.year] = byYear[r.year] || []).push(r);
const years = Object.keys(byYear).sort((a, b) => b - a);
const recentYears = years.filter((y) => y >= "2025").map((y) => ({ year: y, items: byYear[y] }));
const earlyYears = years.filter((y) => y < "2025").map((y) => ({ year: y, items: byYear[y] }));

/* --------------------------------------------------------------------------- index */
{
  // One mark per RELEASE, not per month. 44 releases span 67 months, so 67 undifferentiated
  // marks under the caption "A release lands here every month" would claim 23 months that had
  // no release. The marks carry no filled/empty state, so the honest count is the release count.
  const out = compileDesign(SRC_INDEX, (d) => ({
    ...d,
    pulses: rel.map(() => ({})),
    latest: rel[0],
    recentYears,
    earlyYears,
    earlyCount: earlyYears.reduce((n, y) => n + y.items.length, 0),
  }));

  const $ = cheerio.load(out.html, null, false);

  const latestA = $("a[data-latest]");
  latestA.attr("href", rel[0].href);

  // Document order: recentYears then earlyYears, matching the two sc-for blocks in the design.
  const ordered = [...recentYears, ...earlyYears].flatMap((y) => y.items);
  const rows = $("a.crx-relrow");
  if (rows.length !== ordered.length) {
    console.error(`\nbuild-changelog: ${rows.length} release rows but ${ordered.length} releases. ` +
      `Refusing to guess which href goes where.`);
    process.exit(1);
  }
  rows.each((i, el) => $(el).attr("href", ordered[i].href));
  out.html = $.html();

  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(
    path.join(OUT, "changelog-index.ts"),
    `// GENERATED by scripts/build-changelog.mjs. Do not edit by hand.\n` +
      `export const html = ${JSON.stringify(out.html)};\n` +
      `export const css = ${JSON.stringify(out.css)};\n` +
      `export const script = ${JSON.stringify(out.script)};\n`
  );
  console.log("\nbuild-changelog:");
  console.log(`  ok   changelog-index        ${String(Math.round(out.html.length / 1024)).padStart(4)}KB   ` +
    `${rel.length} releases, ${rows.length} rows wired, latest -> ${rel[0].slug}`);
  if (out.unresolved.length) console.log(`  !!   unresolved: ${out.unresolved.slice(0, 6).join(", ")}`);
}

/* --------------------------------------------------------------------------- entry */
const T = (k) => `@@${k}@@`;
for (const [name, flags] of [
  ["changelog-entry", { hasNext: true, isLatest: false }],
  ["changelog-entry-latest", { hasNext: false, isLatest: true }],
]) {
  const out = compileDesign(SRC_ENTRY, (d) => ({
    ...d,
    post: { month: T("month"), dateLabel: T("dateLabel"), description: T("description") },
    prev: { month: T("prevMonth") },
    next: { month: T("nextMonth") },
    ...flags,
  }));

  const $ = cheerio.load(out.html, null, false);
  const pn = $("a.crx-pn");
  // Previous is always first in the design's grid; Next only exists on the non-latest variant.
  if (pn.length) $(pn[0]).attr("href", T("prevHref"));
  if (pn.length > 1) $(pn[1]).attr("href", T("nextHref"));
  const body = $('[data-slot="body"]');
  if (!body.length) {
    console.error("\nbuild-changelog: no [data-slot=\"body\"] in the entry design, cannot inject release notes.");
    process.exit(1);
  }
  body.html("@@BODY@@");
  out.html = $.html();

  const tokens = [...new Set(out.html.match(/@@[a-zA-Z0-9]+@@/g) || [])];
  fs.writeFileSync(
    path.join(OUT, `${name}.ts`),
    `// GENERATED by scripts/build-changelog.mjs. Do not edit by hand.\n` +
      `export const html = ${JSON.stringify(out.html)};\n` +
      `export const css = ${JSON.stringify(out.css)};\n` +
      `export const script = ${JSON.stringify(out.script)};\n` +
      `export const tokens = ${JSON.stringify(tokens)} as const;\n`
  );
  console.log(`  ok   ${name.padEnd(22)} ${String(Math.round(out.html.length / 1024)).padStart(4)}KB   ` +
    `${pn.length} prev/next, tokens: ${tokens.length}`);
  if (out.unresolved.length) console.log(`  !!   unresolved: ${out.unresolved.slice(0, 6).join(", ")}`);
}
console.log("build-changelog: complete\n");
